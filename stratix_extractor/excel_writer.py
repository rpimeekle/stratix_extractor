"""Write the collected data to an .xlsx workbook and verify it afterwards."""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

from openpyxl import Workbook, load_workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

from . import APP_NAME, __version__
from .collector import SwitchResult

HEADER_FILL = PatternFill("solid", fgColor="1F3864")
HEADER_FONT = Font(bold=True, color="FFFFFF")
STATUS_FILLS = {
    "connected": PatternFill("solid", fgColor="E2EFDA"),
    "err-disabled": PatternFill("solid", fgColor="F8CBAD"),
    "disabled": PatternFill("solid", fgColor="E7E6E6"),
    "Success": PatternFill("solid", fgColor="E2EFDA"),
    "Failed": PatternFill("solid", fgColor="F8CBAD"),
}

SHEETS = ["Summary", "Switches", "Ports", "Inventory", "VLANs", "Neighbours"]
SWITCH_KEY_COLUMNS = ["Switch", "Switch IP"]


@dataclass
class RunInfo:
    started: datetime
    finished: datetime
    input_file: str
    selected: int


def _write_table(sheet, headers: list[str], rows: list[list], wide: dict[str, int] | None = None,
                 status_column: str | None = None) -> None:
    sheet.append(headers)
    for cell in sheet[1]:
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = Alignment(vertical="center")
    for row in rows:
        sheet.append(["" if v is None else v for v in row])

    status_index = headers.index(status_column) + 1 if status_column in headers else None
    if status_index:
        for (cell,) in sheet.iter_rows(min_row=2, min_col=status_index, max_col=status_index):
            fill = STATUS_FILLS.get(str(cell.value))
            if fill:
                cell.fill = fill

    wide = wide or {}
    for col_index, header in enumerate(headers, start=1):
        longest = max([len(str(header))] + [len(str(r[col_index - 1])) for r in rows if col_index - 1 < len(r)])
        cap = wide.get(header, 40)
        sheet.column_dimensions[get_column_letter(col_index)].width = min(max(longest + 2, 8), cap)
    sheet.freeze_panes = "A2"
    if rows:
        sheet.auto_filter.ref = f"A1:{get_column_letter(len(headers))}{len(rows) + 1}"


def _switch_cols(result: SwitchResult) -> list:
    return [result.details.get("Device hostname") or result.target.hostname, result.target.ip]


def write_workbook(path: str | Path, results: list[SwitchResult], info: RunInfo) -> dict[str, int]:
    """Write the workbook and return the number of data rows on each sheet."""
    path = Path(path)
    workbook = Workbook()
    ok = [r for r in results if r.success]

    # ---- Summary
    summary = workbook.active
    summary.title = "Summary"
    summary["A1"] = f"{APP_NAME} report"
    summary["A1"].font = Font(bold=True, size=14)
    meta = [
        ("Run started", info.started.strftime("%Y-%m-%d %H:%M:%S")),
        ("Run finished", info.finished.strftime("%Y-%m-%d %H:%M:%S")),
        ("Duration (s)", round((info.finished - info.started).total_seconds(), 1)),
        ("Switch list", info.input_file),
        ("Switches selected", info.selected),
        ("Switches attempted", len(results)),
        ("Succeeded", len(ok)),
        ("Failed", len(results) - len(ok)),
        ("Generated by", f"{APP_NAME} {__version__}"),
    ]
    for offset, (label, value) in enumerate(meta, start=3):
        summary.cell(row=offset, column=1, value=label).font = Font(bold=True)
        summary.cell(row=offset, column=2, value=value).alignment = Alignment(horizontal="left")
    table_row = len(meta) + 5
    headers = ["Switch", "Switch IP", "Result", "Ports", "Duration (s)", "Error / warnings"]
    for col, header in enumerate(headers, start=1):
        cell = summary.cell(row=table_row, column=col, value=header)
        cell.fill, cell.font = HEADER_FILL, HEADER_FONT
    for offset, r in enumerate(results, start=1):
        notes = "; ".join(([r.error] if r.error else []) + r.warnings)
        values = [r.target.hostname, r.target.ip, "Success" if r.success else "Failed",
                  len(r.ports) if r.success else "", r.duration_s, notes]
        for col, value in enumerate(values, start=1):
            cell = summary.cell(row=table_row + offset, column=col, value=value)
            if col == 3:
                cell.fill = STATUS_FILLS[value]
    for col, width in zip("ABCDEF", (22, 40, 10, 8, 12, 90)):
        summary.column_dimensions[col].width = width
    summary.freeze_panes = summary.cell(row=table_row + 1, column=1)

    counts = {"Summary": len(results)}

    # ---- Switches
    switch_headers = list(ok[0].details.keys()) if ok else ["Hostname (list)", "IP address"]
    _write_table(
        workbook.create_sheet("Switches"),
        switch_headers,
        [[r.details.get(h, "") for h in switch_headers] for r in ok],
        wide={"Image file": 60, "Management IPs": 50, "Software": 45},
    )
    counts["Switches"] = len(ok)

    # ---- Ports
    port_headers = next((list(r.ports[0].keys()) for r in ok if r.ports), ["Port", "Description"])
    port_rows = [_switch_cols(r) + [p.get(h, "") for h in port_headers] for r in ok for p in r.ports]
    _write_table(
        workbook.create_sheet("Ports"),
        SWITCH_KEY_COLUMNS + port_headers,
        port_rows,
        wide={"Description": 80, "Allowed VLANs": 50, "Neighbour": 40, "Neighbour port": 35},
        status_column="Status",
    )
    counts["Ports"] = len(port_rows)

    # ---- Inventory
    inv_rows = [_switch_cols(r) + [i["name"], i["description"], i["pid"], i["vid"], i["serial"]]
                for r in ok for i in r.inventory]
    _write_table(workbook.create_sheet("Inventory"),
                 SWITCH_KEY_COLUMNS + ["Name", "Description", "PID", "VID", "Serial number"],
                 inv_rows, wide={"Description": 80})
    counts["Inventory"] = len(inv_rows)

    # ---- VLANs
    vlan_rows = [_switch_cols(r) + [v["vlan"], v["name"], v["status"], v["ports"]]
                 for r in ok for v in r.vlans]
    _write_table(workbook.create_sheet("VLANs"),
                 SWITCH_KEY_COLUMNS + ["VLAN", "Name", "Status", "Ports"],
                 vlan_rows, wide={"Ports": 90})
    counts["VLANs"] = len(vlan_rows)

    # ---- Neighbours
    nbr_rows = [_switch_cols(r) + [n["local_interface"], n["protocol"], n["device"], n["remote_port"],
                                   n["ip"], n["platform"], n.get("chassis_id", ""), n["capabilities"],
                                   n["description"]]
                for r in ok for n in r.neighbours]
    _write_table(workbook.create_sheet("Neighbours"),
                 SWITCH_KEY_COLUMNS + ["Local port", "Protocol", "Neighbour", "Neighbour port",
                                       "Neighbour IP", "Platform", "Chassis ID", "Capabilities",
                                       "Description"],
                 nbr_rows, wide={"Description": 90})
    counts["Neighbours"] = len(nbr_rows)

    workbook.properties.creator = f"{APP_NAME} {__version__}"
    workbook.save(path)
    return counts


def verify_workbook(path: str | Path, expected: dict[str, int]) -> tuple[bool, str]:
    """Re-open the saved file and check every sheet has the expected rows."""
    try:
        workbook = load_workbook(path, read_only=True)
    except Exception as exc:
        return False, f"Saved file could not be re-opened: {exc}"
    try:
        problems = []
        for name in SHEETS:
            if name not in workbook.sheetnames:
                problems.append(f"sheet '{name}' missing")
                continue
            if name == "Summary":
                continue
            sheet = workbook[name]
            data_rows = sum(1 for row in sheet.iter_rows(min_row=2, values_only=True) if any(row))
            if data_rows != expected.get(name, 0):
                problems.append(f"{name}: expected {expected.get(name, 0)} rows, found {data_rows}")
        if problems:
            return False, "; ".join(problems)
        return True, ", ".join(f"{name} {expected.get(name, 0)}" for name in SHEETS[1:])
    finally:
        workbook.close()


def check_writable(path: str | Path) -> str | None:
    """Return an error message if the output file can't be written (e.g. it's
    open in Excel), otherwise None. Leaves no file behind."""
    path = Path(path)
    if not path.parent.exists():
        return f"Folder does not exist: {path.parent}"
    if path.exists():
        try:
            with open(path, "a+b"):
                pass
        except PermissionError:
            return f"{path.name} is open in another program (probably Excel). Close it and try again."
        except OSError as exc:
            return f"Cannot write {path}: {exc}"
    else:
        try:
            with open(path, "wb"):
                pass
            path.unlink()
        except OSError as exc:
            return f"Cannot create {path}: {exc}"
    return None
